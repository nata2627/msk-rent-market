-- ---------------------------------------------------------------------
-- 12.11.2026. Состояние квартиры и дома по последнему снимку выдачи:
-- слова описания о ремонте, длина описания, дом под реновацию.
--
-- Типа ремонта в выдаче нет (repairType пуст у всех), а обход страниц
-- объявлений отменён. Описание же в выдаче есть всегда, и в нём
-- продавец сам говорит о ремонте. Правила, а не разбор смысла: каждое
-- можно проверить глазами на любом объявлении.
--
-- Рынок со словами согласен. Медиана цены метра к похожим на 26 090
-- активных 12.11: «дизайнерский» 1,21 против 0,99 без него, «свежий,
-- новый ремонт» 1,09, «новая мебель, техника» 1,07, «косметический»
-- 0,92 против 1,03, «старый ремонт, мебель» 0,74, «без ремонта» 0,70.
-- «Евроремонт» 1,03 против 1,02: пишут почти все, рынок не доплачивает.
--
-- Шкала моя (26.09): дизайнерский 100, евро 80, косметический 25, без
-- ремонта 10. Косметический это обшарпанное, а не середина.
--
-- Не берутся «советский» (Советский район и улицы) и «бабушкин»: из
-- 477 совпадений почти все это станция Бабушкинская или «никакого
-- бабушкиного ремонта». У «старой мебели» и «без ремонта» отсекаются
-- отрицание и балкон с лоджией.
--
-- Порядок проверки важен. Плохие слова перебивают хорошие, потому что
-- «евроремонт» пишут по привычке, а «требует ремонта» по нужде.
-- «Косметический» стоит раньше «нового ремонта»: «свежий косметический
-- ремонт» это всё равно косметический. «Лучше, чем на фото» проверяется
-- последним: так пишут и про ухоженные квартиры с плохими снимками, и
-- тогда рядом стоит «новая мебель» или «качественный ремонт». Без
-- хороших слов это повод насторожиться (метр 0,92 от похожих), но не
-- приговор.
--
-- Реновация. Дом в московской программе сноса (почти всегда пятиэтажка
-- 1950-60-х): метр 0,92 от похожих против 1,02, у 3% рынка и у 10% моего
-- отбора. Флаг ставит сама площадка.
--
-- Короткое описание. Меньше 300 знаков у 12% рынка, метр 0,94 против
-- 1,03: продавцу нечего сказать о квартире. Признак слабый, поэтому
-- работает только там, где слов о ремонте нет вовсе.
-- ---------------------------------------------------------------------
with d as (
select o.source, o.offer_id, lower(s.payload->>'description') as d,
       coalesce((s.payload->>'demolishedInMoscowProgramm')::boolean, false) as is_renovation
  from {{ source('core', 'offer') }} o
  -- Последний снимок с телом: у повторов тело пустое и есть ссылка
  -- same_as, а содержимое у них то же самое.
  left join lateral (
       select payload
         from {{ source('raw', 'offer_snapshot') }} s
        where s.source = o.source and s.offer_id = o.offer_id
          and s.payload is not null
        order by s.snapshot_date desc, s.snapshot_id desc
        limit 1) s on true
)
select source, offer_id,
       case when d ~ '((?<!балкон )(?<!лоджия )без ремонта|(?<!никак\w{1,3} )(?<!нет )стар\w* (ремонт|мебел)|требует\s+(косметическ\w*\s+)?ремонт)'
                                                                   then 'плохой'
            when d ~ 'дизайнерск'                                  then 'дизайнерский'
            when d ~ 'евроремонт'                                  then 'евроремонт'
            when d ~ 'косметическ'                                 then 'косметический'
            when d ~ '((свеж\w*|нов\w*|современн\w*) ремонт|нов\w* (мебел|техник))'
                                                                   then 'новый'
            when d ~ 'лучше\s*,?\s*чем на фото'                    then 'фото хуже'
            end as repair_text
     , coalesce(length(d), 0) < 300 as is_short_description
     , is_renovation
  from d
