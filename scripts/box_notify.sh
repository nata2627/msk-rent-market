#!/bin/bash
# Докладывание о беде наружу: одно короткое сообщение в личный канал.
#
# Зачем. 21.10.2026 заклинивший обход девятнадцать часов держал замок и
# почти съел день панели; дашборд до 22.10.2026 десять дней показывал
# мёртвую копию базы. Оба раза всё было правильно записано в журналы — и
# оба раза о беде узнали только потому, что спросили сами. Журнал,
# который никто не читает, беду не предотвращает: нужен толчок наружу.
#
# Как зовут:
#   scripts/box_notify.sh <ключ-события> <текст одной строкой>
#   scripts/box_notify.sh --always <ключ> <текст>   # без ограничения частоты
#   scripts/box_notify.sh --test                    # разовая проверка канала
#
# Ключ события — не украшение: по нему работает ограничение частоты.
# Одна беда — один ключ, иначе сторож, который ходит раз в двадцать
# минут, пришлёт одну и ту же строку семьдесят два раза за сутки.
#
# Чего этот скрипт НЕ делает: не падает. Нет настроек, нет сети, канал
# ответил отказом — пишет одну строку в data/logs/box_notify.log и
# выходит с нулём. Уведомление не имеет права стать новой причиной
# потерять день. Ненулевой код возвращает только `--test`: это ручная
# проверка, и она обязана говорить правду громко.
#
# Транспорт. Готового канала не нашлось ни в соседнем проекте на макбуке
# (moex, ~/Desktop/my_jobs/sql_p — там только Metabase, уведомлений нет),
# ни в боксе сбора, а второй бокс Mac mini чужой и ключа к нему нет.
# Регистрировать бота или учётку за владелицу нельзя, поэтому
# поддержаны оба очевидных способа, и выбирает тот, что заполнен в .env:
#
#   NOTIFY_NTFY_URL  — публикация в ntfy (учётка не нужна, секрет — само
#                      имя топика), например https://ntfy.sh/<своё-длинное-слово>
#   NOTIFY_TG_TOKEN + NOTIFY_TG_CHAT — бот телеграма
#
# Ничего не настроено — беда по-прежнему попадает в журналы, и ровно это
# скрипт о себе и пишет. Секреты только в .env, образец в .env.example:
# репозиторий публичный.

set -uo pipefail

# Машина живёт по UTC, а панель московская: без этого в сообщении стояло
# бы время на три часа младше, чем в журналах прогона.
export TZ=Europe/Moscow

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Пути через переменные — чтобы тесты не писали в рабочий журнал и не
# трогали настоящие отметки частоты.
ENV_FILE="${NOTIFY_ENV_FILE:-$REPO/.env}"
LOG_DIR="${NOTIFY_LOG_DIR:-$REPO/data/logs}"
STATE_DIR="${NOTIFY_STATE_DIR:-$REPO/data/notify}"
mkdir -p "$LOG_DIR" "$STATE_DIR" 2>/dev/null

LOG="$LOG_DIR/box_notify.log"
note() { echo "$(date '+%d.%m %H:%M') $*" >>"$LOG" 2>/dev/null; }

# .env читается разбором, а не `source`: файл с секретами исполнять
# незачем, а опечатка в нём тогда превращается в запуск чего угодно от
# имени прогона.
from_env() {
  [ -f "$ENV_FILE" ] || return 0
  sed -n "s/^[[:space:]]*$1=//p" "$ENV_FILE" | tail -n 1 \
    | sed -e 's/[[:space:]]*$//' -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'\$/\1/"
}

# Переменная окружения сильнее .env: так проверяют канал разово, не
# трогая файл на машине.
NTFY_URL="${NOTIFY_NTFY_URL:-$(from_env NOTIFY_NTFY_URL)}"
TG_TOKEN="${NOTIFY_TG_TOKEN:-$(from_env NOTIFY_TG_TOKEN)}"
TG_CHAT="${NOTIFY_TG_CHAT:-$(from_env NOTIFY_TG_CHAT)}"

# Окно ограничения частоты: одно сообщение на тип события за N часов.
#
# Шесть часов — не круглое число, а ровно срок давности замка из
# box_watch.sh. Рассуждение то же: шесть часов вдвое дольше самого
# долгого честного обхода, поэтому беда, пережившая окно, — это уже не
# та же беда, а новая, и сказать о ней стоит снова. Считая так, худший
# день даёт четыре сообщения на тип события и около двадцати на все
# пять — это ещё читают. Окно короче ночи: беда, начавшаяся в два часа,
# напомнит о себе к восьми, а не промолчит до вечера.
#
# Меньше взять нельзя — сторож ходит раз в двадцать минут, и час дал бы
# двадцать четыре сообщения об одном заклинившем замке. Больше взять
# нельзя — сутки означают, что вторая беда за день приходит молча.
WINDOW_H="${NOTIFY_WINDOW_H:-$(from_env NOTIFY_WINDOW_H)}"
WINDOW_H="${WINDOW_H:-6}"

TEST=0
ALWAYS=0
if [ "${1:-}" = "--test" ]; then
  TEST=1
  ALWAYS=1
  KEY="test"
  TEXT="проверка канала rent_msk: $(date '+%d.%m.%Y %H:%M'), машина $(hostname)"
else
  if [ "${1:-}" = "--always" ]; then ALWAYS=1; shift; fi
  KEY="${1:-прочее}"
  shift 2>/dev/null
  TEXT="$*"
fi

if [ -z "${TEXT//[[:space:]]/}" ]; then
  note "пустое сообщение с ключом «${KEY}», отправлять нечего"
  exit 0
fi

# Настроенные каналы берутся ВСЕ, а не первый попавшийся.
#
# Сначала был выбор одного, с ntfy в приоритете, — и это ошибка того же
# рода, что лечит вся эта обвязка. Читают обычно один канал; если беда
# уйдёт в тот, на который владелица не подписана, она снова узнает о
# потерянном дне, только спросив. Сообщений единицы в сутки, дубль
# дешевле пропажи.
TRANSPORTS=""
[ -n "$NTFY_URL" ] && TRANSPORTS="ntfy"
[ -n "$TG_TOKEN" ] && [ -n "$TG_CHAT" ] && TRANSPORTS="${TRANSPORTS:+$TRANSPORTS }telegram"

if [ -z "$TRANSPORTS" ]; then
  note "канал не настроен, сообщение осталось здесь («${KEY}»): $TEXT"
  if [ "$TEST" = 1 ]; then
    echo "Канал уведомлений НЕ настроен — беда пишется только в журналы."
    echo "Нужно одно из двух в $ENV_FILE:"
    echo "  NOTIFY_NTFY_URL=https://ntfy.sh/<своё-секретное-слово>"
    echo "  NOTIFY_TG_TOKEN=<токен бота> вместе с NOTIFY_TG_CHAT=<id чата>"
    echo "Образец и пояснения — .env.example."
    exit 1
  fi
  exit 0
fi

# Ограничение частоты. Отметка — пустой файл на тип события, время
# берётся из его mtime: ни базы, ни разбора формата, и состояние
# переживает перезапуск бокса. Имя обеззараживается, потому что ключ
# приходит из вызывающего скрипта и не обязан быть именем файла.
STAMP="$STATE_DIR/$(printf '%s' "$KEY" | tr -c 'A-Za-z0-9._-' '_')"
if [ "$ALWAYS" = 0 ] && [ -f "$STAMP" ]; then
  # stat -c для Linux (бокс), stat -f для macOS (макбук): скрипт живёт
  # в одном репозитории на обеих машинах.
  MTIME="$(stat -c %Y "$STAMP" 2>/dev/null || stat -f %m "$STAMP" 2>/dev/null || echo 0)"
  AGE_MIN=$(( ( $(date +%s) - MTIME ) / 60 ))
  if [ "$AGE_MIN" -lt $(( WINDOW_H * 60 )) ]; then
    note "подавлено, «${KEY}» уходил $AGE_MIN мин назад (окно $WINDOW_H ч): $TEXT"
    exit 0
  fi
fi

# Разметка сообщения. Договор простой, чтобы места вызова читались
# глазами как обычный текст:
#   первая строка         — заголовок, в телеграме уходит жирным;
#   строка, начатая «$ »  — команда, уходит моноширинной;
#   остальное             — как есть.
#
# Зачем вообще. Первые сообщения были одной длинной строкой: дата,
# беда, числа и команда лечения подряд. На телефоне это читается
# предложением, а не сводкой, и главное — что именно случилось —
# тонет в середине. Беду надо понимать за секунду, иначе уведомление
# не лучше журнала, который никто не открывает.
#
# Журнал и ntfy остаются простым текстом: разметка телеграма в них
# показалась бы сырыми тегами.
to_html() {
  python3 -c '
import html, sys
lines = sys.stdin.read().rstrip("\n").split("\n")
out = []
for i, line in enumerate(lines):
    safe = html.escape(line)
    if i == 0:
        out.append(f"<b>{safe}</b>")
    elif line.startswith("$ "):
        out.append(f"<code>{html.escape(line[2:])}</code>")
    else:
        out.append(safe)
print("\n".join(out))
'
}

# Для ntfy и журнала — тот же текст без служебного «$ » у команд.
to_plain() { sed 's/^\$ //'; }

# Сроки жёсткие и маленькие: сеть в боксе бывает мертва, а прогон ждать
# уведомления не должен. Худший случай — около двадцати секунд на канал.
ERR_FILE="$(mktemp 2>/dev/null || echo "/tmp/box_notify.$$.err")"
DELIVERED=0
REPORT=""

for TRANSPORT in $TRANSPORTS; do
  case "$TRANSPORT" in
    ntfy)
      CODE="$(curl -sS -o /dev/null -w '%{http_code}' \
        --connect-timeout 5 --max-time 10 --retry 1 --retry-delay 3 \
        -H 'Title: rent_msk' -H 'Priority: high' -H 'Tags: house' \
        --data-binary "$(printf '%s' "$TEXT" | to_plain)" "$NTFY_URL" 2>"$ERR_FILE")"
      # Цель печатается урезанной: у ntfy секрет — само имя топика.
      TARGET="ntfy, топик $(printf '%s' "${NTFY_URL##*/}" | cut -c1-3)***"
      ;;
    telegram)
      CODE="$(curl -sS -o /dev/null -w '%{http_code}' \
        --connect-timeout 5 --max-time 10 --retry 1 --retry-delay 3 \
        -d "chat_id=$TG_CHAT" -d 'disable_web_page_preview=true' \
        -d 'parse_mode=HTML' \
        --data-urlencode "text=$(printf '%s' "$TEXT" | to_html)" \
        "https://api.telegram.org/bot$TG_TOKEN/sendMessage" 2>"$ERR_FILE")"
      # У телеграма секрет — всё после двоеточия в токене.
      TARGET="телеграм, чат $TG_CHAT, бот ${TG_TOKEN%%:*}:***"
      ;;
  esac
  CODE="${CODE:-000}"

  # Ругань curl чистится от секретов до того, как попадёт в журнал:
  # журнал переливается вместе с данными и читается глазами.
  ERR="$(tr '\n' ' ' <"$ERR_FILE" 2>/dev/null)"
  [ -n "$TG_TOKEN" ] && ERR="${ERR//$TG_TOKEN/***}"
  [ -n "$NTFY_URL" ] && ERR="${ERR//$NTFY_URL/***}"
  : >"$ERR_FILE"

  case "$CODE" in
    2??) DELIVERED=$(( DELIVERED + 1 ))
         note "отправлено ($TRANSPORT, код $CODE, «${KEY}»): $(printf '%s' "$TEXT" | to_plain | tr '\n' ' ')" ;;
    *)   note "НЕ отправлено ($TRANSPORT, код $CODE${ERR:+, $ERR}), «${KEY}»: $TEXT" ;;
  esac
  REPORT="${REPORT}${TARGET}|${CODE}|${ERR}
"
done
rm -f "$ERR_FILE"

# Отметка ставится, если дошло ХОТЯ БЫ ОДНО. Иначе упавший канал заглушил
# бы беду на целое окно ровно тогда, когда каналу и без того нехорошо.
[ "$ALWAYS" = 0 ] && [ "$DELIVERED" -gt 0 ] && touch "$STAMP"
[ "$DELIVERED" = 0 ] && note "ни один канал не принял «${KEY}», сообщение осталось здесь: $TEXT"

if [ "$TEST" = 1 ]; then
  printf '%s' "$REPORT" | while IFS='|' read -r target code err; do
    [ -z "$target" ] && continue
    case "$code" in
      2??) echo "ДОШЛО: $target (код $code)" ;;
      000) echo "НЕ ДОШЛО: $target — канал не ответил вовсе${err:+ ($err)}" ;;
      *)   echo "НЕ ДОШЛО: $target — код $code${err:+ ($err)}" ;;
    esac
  done
  if [ "$DELIVERED" = 0 ]; then
    echo "Ни один канал не принял сообщение."
    exit 1
  fi
  echo "Каналов настроено: $(printf '%s' "$TRANSPORTS" | wc -w | tr -d ' '), доставлено: $DELIVERED. Посмотрите в канале."
fi

# Беда наружу доложена или не доложена, но прогон из-за этого не падает.
exit 0
