#!/bin/bash
# Срез дня, если макбук был ВЫКЛЮЧЕН в 11:00.
#
# Пропущенный из-за сна запуск launchd выполняет при пробуждении, а
# пропущенный из-за выключения теряет молча: 31.10.2026 макбук включили в
# 11:32, и среза за день не было, пока его не запустили руками. Эта задача
# срабатывает при входе в систему (RunAtLoad) и решает, нужен ли срез.
#
# Не запускает, если:
#   * ещё нет 11:00 (плановый запуск впереди);
#   * за сегодня уже есть лог daily.sh. Даже прерванный прогон считается:
#     его могли остановить намеренно, и повтор при каждом входе мешал бы;
#   * держится замок (прогон уже идёт).
# После среза запускает хвост дня, если он не прошёл сам: хвост 14:00 ждёт
# замок не больше часа и потом пропускает день.

set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 1
LOG_DIR="$REPO/data/logs"; mkdir -p "$LOG_DIR"
exec >>"$LOG_DIR/mac_boot_catchup_$(date +%Y%m).log" 2>&1
say() { echo "$(date '+%d.%m %H:%M:%S') === $*"; }

if [ "$(date +%-H)" -lt 11 ]; then
  say "Вход до 11:00, срез сделает плановый запуск"; exit 0
fi
if ls "$LOG_DIR"/daily_"$(date +%Y%m%d)"_*.log >/dev/null 2>&1; then
  say "Срез за сегодня уже был, ничего не делаю"; exit 0
fi
if [ -d "$REPO/data/daily.lock" ]; then
  say "Замок занят, прогон уже идёт"; exit 0
fi

say "Среза за сегодня нет, запускаю daily.sh"
START="$(date +%H:%M:%S)"
/bin/bash "$REPO/scripts/daily.sh"
say "daily.sh закончил (код $?)"

# Хвост прошёл сам после начала среза? Строки лога хвоста начинаются с
# «ДД.ММ ЧЧ:ММ:СС», время сравнивается как строка.
TODAY="$(date +%d.%m)"
if awk -v d="$TODAY" -v s="$START" '$1==d && $2>=s && /=== Конец/ {f=1} END {exit !f}' \
     "$LOG_DIR/mac_tail_$(date +%Y%m).log" 2>/dev/null; then
  say "Хвост уже прошёл после среза"
else
  say "Запускаю хвост"
  /bin/bash "$REPO/scripts/mac_tail.sh"
  say "Хвост закончил (код $?)"
fi
