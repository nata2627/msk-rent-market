#!/bin/bash
# Ежедневный прогон панели. Запускается по расписанию через launchd,
# руками — тоже (./scripts/daily.sh).
#
# Почему именно launchd, а не cron. Сбор идёт через настоящий Chrome с
# видимым окном: в headless площадка отвечает 403. Значит нужен живой
# графический сеанс. launchd как раз запускает задачи пользователя в его
# сеансе, а пропущенный из-за сна компьютера запуск выполняет при
# пробуждении. cron на macOS для этого не годится.
#
# Порядок шагов не случайный. Сбор первый и единственный обязательный:
# несобранный день потерян навсегда, всё остальное пересчитывается из
# raw когда угодно. Поэтому дальше идёт цепочка, где падение любого
# шага записывается в журнал, но не мешает следующему.

set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 1

# Не давать компьютеру уснуть, пока идёт обход.
#
# 28.09.2026 плановый прогон за два часа прошёл 43 корзины из 294 вместо
# полутора часов на все. Провалы в журнале — 944, 956, 989, 1011 секунд —
# слово в слово совпали с циклами Maintenance Sleep в `pmset -g log`:
# в настройках стоит сон после минуты простоя, а счёт процессора сам по
# себе простоем быть не перестаёт. Браузер засыпал вместе с системой.
#
# Заметить это по журналу сбора невозможно: строки просто идут с
# получасовыми паузами, будто площадка задумалась.
#
# -i не даёт уснуть по простою, -s держит систему при питании от сети,
# -m не даёт заснуть диску. Закрытая крышка всё равно усыпит — это
# сильнее любых утверждений процесса.
if [ -z "${UNDER_CAFFEINATE:-}" ]; then
  export UNDER_CAFFEINATE=1
  exec caffeinate -i -s -m "$0" "$@"
fi

PY="$REPO/.venv/bin/python"
STAMP="$(date +%Y%m%d_%H%M)"
LOG_DIR="$REPO/data/logs"
LOG="$LOG_DIR/daily_$STAMP.log"
mkdir -p "$LOG_DIR"

exec >>"$LOG" 2>&1

say() { echo "$(date +%H:%M:%S) === $*"; }

# Не начинать обход от батареи.
#
# 04.10.2026 прогон собрал ноль объявлений. launchd разбудил его в 12:14
# внутри окна тёмного пробуждения, caffeinate поставил блокировку в
# 12:14:21, а в 12:14:22 система ушла обратно в сон на 1071 секунду,
# потом ещё на 564. Браузер проснулся без сети, и `goto` отвалился по
# таймауту в 60 секунд.
#
# Дело в питании. `caffeinate -s` действует только от сети, и на батарее
# утверждение просто ничего не значит. А `-i` тут бессилен и от сети:
# система не считала нас простоем, она дозасыпала прерванный сон, и этому
# утверждения процессов не указ.
#
# Проверять надо до обхода, а не разбирать журнал после. В журнале того
# сбоя виден таймаут на первой же странице — ровно так выглядит
# блокировка площадки, то есть совсем другая болезнь с совсем другим
# лечением. Причину надо назвать до того, как она переоденется.
#
# Ждём шнур, а не выходим сразу: несобранный день потерян навсегда, а
# воткнуть шнур можно и через час. Ожидание стоит ДО замка, иначе оно
# отодвинет недельный добор, который ждёт того же замка.
AC_WAIT_MIN=180

on_ac() {
  # Нет pmset — значит не macOS, и проверять нечего.
  command -v pmset >/dev/null 2>&1 || return 0
  [[ "$(pmset -g batt)" == *"'AC Power'"* ]]
}

if ! on_ac; then
  say "Питание от батареи, обход не начинаю. Жду шнур до $AC_WAIT_MIN мин."
  for _ in $(seq 1 "$AC_WAIT_MIN"); do
    sleep 60
    if on_ac; then say "Питание от сети появилось, продолжаю"; break; fi
  done
  if ! on_ac; then
    say "ОШИБКА: за $AC_WAIT_MIN мин питание от сети не появилось. Прогон отменён."
    echo "$(date +%F\ %H:%M)  сбоев: 1  прогон отменён, питание от батареи" \
      >> "$LOG_DIR/daily_summary.log"
    exit 1
  fi
fi

# Один прогон за раз. Обход идёт около часа; если предыдущий ещё жив,
# второй браузер в том же профиле сломает сессию обоим.
LOCK="$REPO/data/daily.lock"
if ! mkdir "$LOCK" 2>/dev/null; then
  say "Предыдущий прогон ещё идёт ($LOCK). Выхожу."
  exit 0
fi
trap 'rmdir "$LOCK" 2>/dev/null' EXIT

say "Начало, дата снимка $(date +%F)"
# Время начала после ожидания шнура: по нему конец прогона решает, видел
# ли хвост дня сегодняшний срез.
COLLECT_START="$(date +%H:%M:%S)"

# Сам демон Docker. Без него `docker compose up -d` не поднимет ничего:
# именно так потерялся день 26.09.2026 — launchd отработал в срок, но
# Docker Desktop не был запущен, и прогон час ждал базу впустую.
# Запускается через open: Docker Desktop — приложение, а не служба.
if ! docker info >/dev/null 2>&1; then
  say "Демон Docker не отвечает, запускаю Docker Desktop"
  open -a Docker 2>/dev/null || say "не удалось запустить Docker Desktop"
  for i in $(seq 1 60); do
    docker info >/dev/null 2>&1 && { say "Демон Docker готов"; break; }
    sleep 5
  done
fi

# Docker с автозапуском поднимается не мгновенно. Ждём базу, а не падаем.
for i in $(seq 1 30); do
  if docker compose exec -T postgres pg_isready -q 2>/dev/null; then break; fi
  [ "$i" = 1 ] && { say "База не отвечает, поднимаю"; docker compose up -d; }
  sleep 10
done
if ! docker compose exec -T postgres pg_isready -q 2>/dev/null; then
  say "ОШИБКА: база так и не поднялась. Прогон отменён."
  exit 1
fi

FAILED=0

step() {
  local name="$1"; shift
  say "$name"
  if "$@"; then
    say "$name — готово"
  else
    say "$name — СБОЙ (код $?), иду дальше"
    FAILED=$((FAILED + 1))
  fi
}

# Сбор. Единственный шаг, который нельзя нагнать задним числом.
# --no-collect пропускает его: так проверяется обвязка, не беспокоя площадку.
if [ "${1:-}" = "--no-collect" ]; then
  say "Сбор пропущен (--no-collect)"
else
  step "Сбор"          "$PY" -m etl.collect --mode narrow --transport browser
fi

# Всё дальше пересчитывается из raw в любой момент.
step "Справочник"      "$PY" -m etl.districts
step "Парки и МКАД"    "$PY" -m etl.parks
step "Дедупликация"    "$PY" -m src.dedup
step "Витрины"         make -s marts

# Проверка ДО индекса и подстановки: если эти файлы уже изменены, значит их
# правит человек, и автоматический коммит смёл бы недописанное в историю.
# Числа всё равно подставим, они не мешают, а коммит оставим человеку.
# Индекс входит в список с 02.11.2026: файлы от 28.10 устаревали, и README
# с витриной показывали индекс недельной давности.
NUM_PATHS=(README.md methods results/panel_index.json results/panel_index_3.json
           figures/panel_index.png figures/panel_index_3.png)
if git -C "$REPO" diff --quiet -- "${NUM_PATHS[@]}"; then
    README_WAS_CLEAN=1
else
    README_WAS_CLEAN=0
fi

# Индекс пересчитывается каждый день: минута счёта, а README и витрина берут
# его из results/. Прогноз сюда не входит, он строится по месячному ряду
# Росстата и меняется только с новым месяцем.
step "Индекс"          make -s index

say "Конец"

# Журналы старше двух месяцев не нужны: всё существенное лежит в raw.bucket.
find "$LOG_DIR" -name 'daily_*.log' -mtime +60 -delete 2>/dev/null

# Короткая сводка в отдельный файл — чтобы не листать часовой журнал.
SUMMARY="$(grep -E 'Итог:' "$LOG" | tail -1 | sed 's/^[0-9:]* INFO //')"
echo "$(date +%F\ %H:%M)  сбоев: $FAILED  ${SUMMARY:-сбор не выполнялся}" \
  >> "$LOG_DIR/daily_summary.log"

# Числа README подставляются из базы и коммитятся сами.
#
# С 05.10.2026 это постоянное правило: решать каждый день про один и
# тот же коммит одного и того же файла незачем. Остальное коммитится
# руками, исключение ровно одно, и оно здесь.
#
# Три ограничения, без которых такое самокоммитание опасно:
#
# 1. В коммит идут ТОЛЬКО README.md, methods/ и файлы индекса цен (числа
#    в methods/ подставляет тот же src.readme_numbers с 24.10.2026; без
#    них они висели незакоммиченными после каждого прогона). Никаких
#    `git add -A`: в рабочем дереве могут лежать чужие правки, и смести
#    их в автоматический коммит — худшее, что может сделать фоновый скрипт.
# 2. Пуша нет. Наружу уходит только руками.
# 3. Если файл не изменился, коммита не будет. Пустые коммиты каждый
#    день засоряют историю и прячут настоящие изменения.
say "Числа README"

if "$PY" -m src.readme_numbers >/dev/null 2>&1; then
    if [ "$README_WAS_CLEAN" = 0 ]; then
        say "Числа README — подставлены, но в файле есть чужие правки, не коммичу"
    elif git -C "$REPO" diff --quiet -- "${NUM_PATHS[@]}"; then
        say "Числа README — без изменений, коммит не нужен"
    elif [ -d "$REPO/.git/rebase-merge" ] || [ -d "$REPO/.git/rebase-apply" ] \
         || [ -f "$REPO/.git/MERGE_HEAD" ]; then
        # Посреди слияния или перебазирования коммитить нельзя: получится
        # не то, что человек начал делать руками.
        say "Числа README — идёт слияние или перебазирование, не коммичу"
    else
        git -C "$REPO" add -u -- "${NUM_PATHS[@]}"
        git -C "$REPO" commit -q -m "Числа панели за $(date +%d.%m.%Y)" \
            && say "Числа README — закоммичено" \
            || say "Числа README — коммит не прошёл"
    fi
else
    say "Числа README — СБОЙ подстановки, README не тронут"
    FAILED=$((FAILED + 1))
fi

# Хвост дня на макбуке (mac_tail.sh, launchd в 14:00) выгружает витрину,
# облачную копию и итог дня. Срез, который ждал шнур, может кончиться
# позже: 09.11.2026 шнур дали в 14:22, хвост в 14:15 не увидел замка и
# выгрузил вчерашнее. А срез длиннее трех часов хвост пропускает сам. В
# обоих случаях после 14:00 хвост сегодня не брал витрину после начала
# среза, и прогон запускает его еще раз. Сравнивается начало выгрузки
# витрины, а не конец хвоста: 09.11 хвост кончился в 14:26, после начала
# среза, а данные взял в 14:15, до него. Через launchd: хвост переживает конец
# этого скрипта, ждет снятия замка, а уже идущий второй раз не стартует.
TAIL_LABEL="com.nata2627.rent-msk.tail"
if [ "$(date +%H)" -ge 14 ] && [ -n "${COLLECT_START:-}" ] \
   && launchctl print "gui/$(id -u)/$TAIL_LABEL" >/dev/null 2>&1; then
  LAST_TAIL="$(grep "^$(date +%d.%m) .* === Витрина$" "$LOG_DIR/mac_tail_$(date +%Y%m).log" 2>/dev/null \
               | tail -1 | cut -c7-14)"
  if [ -z "$LAST_TAIL" ] || [[ "$LAST_TAIL" < "$COLLECT_START" ]]; then
    launchctl kickstart "gui/$(id -u)/$TAIL_LABEL" \
      && say "Хвост дня прошел до среза или не прошел, запущен заново" \
      || say "Хвост дня не запустился, витрина за сегодня не выгружена"
  fi
fi

# Код возврата честный: launchd показывает его в `make schedule-status`,
# и он должен означать «что-то не сделалось», а не «grep ничего не нашёл».
exit $((FAILED > 0 ? 1 : 0))
