#!/bin/bash
# Сторож: ловит окно, когда площадка отдаёт выдачу, и запускает обход.
#
# Зачем. После аварии 11.10.2026 ЦИАН отвечает рывками: выдача даётся
# примерно в одном запросе из десяти, остальные возвращают код 553 и
# страницу в 178 байт. Проверено 12.10.2026 на обеих машинах разом —
# макбук с профилем на 68 кук и Mac mini с чистым получили один и тот же
# отказ в одну минуту, то есть дело не в машине и не в куках. Обход,
# запущенный по часам, в такие сутки тратит попытки впустую, а день
# панели теряется.
#
# Поэтому обход запускается не по расписанию, а по факту: раз в двадцать
# минут делается одна проба, и как только она проходит — идёт полный
# обход. Проба стоит два запроса, это меньше, чем одна корзина обхода.
#
# Ставится в cron рядом с ежедневным прогоном:
#   */20 * * * * /home/dev2/rent_msk/scripts/box_watch.sh
#
# Сам себя сторож выключает: как только за сегодня собрано достаточно,
# он молча выходит, не трогая площадку вовсе.

set -uo pipefail

export TZ=Europe/Moscow

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 1

IMAGE="rent-collector:latest"
PG_CONTAINER="rent_pg"
COLLECT_CONTAINER="rent_collect"

# Срок давности замка и порог тишины в журнале — см. разбор ниже, у
# самой проверки. Через переменные окружения, чтобы проверять логику, не
# трогая файл.
STALE_H="${WATCH_LOCK_STALE_H:-6}"
QUIET_MIN="${WATCH_LOG_QUIET_MIN:-30}"

# Сколько объявлений считать достаточным, чтобы день был собран.
#
# Считается ТОЛЬКО искомый сегмент — одно- и двухкомнатные, те самые
# NARROW_ROOM_CODES. Это важнее, чем кажется: сторож запускает полный
# обход, а он даёт около 25 тысяч против 16 тысяч узкого дня. 13.10.2026
# счёт по всем комнатностям дошёл до 13 410 и порог взялся, тогда как
# одно- и двухкомнатные стояли на 54% нормы — сторож замолчал на половине
# дня. Порог, считанный по тому, ради чего затеян проект, такого не даёт.
#
# Величина: норма сегмента около 16,5 тысяч, порог ниже намеренно —
# лучше оставить в покое неполный, но содержательный день, чем гонять
# обход по кругу ради последних процентов.
ENOUGH="${WATCH_ENOUGH:-12000}"

LOG_DIR="$REPO/data/logs"
mkdir -p "$LOG_DIR"
WATCH_LOG="$LOG_DIR/box_watch.log"

note() { echo "$(date '+%d.%m %H:%M') $*" >>"$WATCH_LOG"; }

# Журнал сторожа живёт год: это одна строка в двадцать минут, но он
# единственный след того, в какие часы площадка была жива.
find "$LOG_DIR" -name 'box_watch.log' -mtime +365 -delete 2>/dev/null

# Доклад наружу. Каждая строка ВНИМАНИЕ и ОСТАНОВКА ниже пишется в
# журнал и тем же вызовом уходит в канал: 21.10.2026 всё было в журнале
# правильно, и ровно поэтому день почти потерялся — журнал никто не
# читал. Отправщик сам молчит, если канал не настроен, сам не даёт одной
# беде улететь семьдесят два раза за сутки и сам не падает, поэтому
# вызов ничем не обёрнут и код его не проверяется.
notify() { bash "$REPO/scripts/box_notify.sh" "$@" >/dev/null 2>&1; }

# Норма искомого сегмента за день, замер 13-21.10.2026: 16-17 тысяч
# одно- и двухкомнатных. Нужна только в сообщениях — чтобы число
# «собрано 3080» сразу читалось как беда, а не как число. Порог самого
# сторожа ниже и живёт в ENOUGH, это разные величины: ENOUGH говорит,
# когда перестать трогать площадку, NORM — насколько день полон.
# Та же величина в box_report.sh.
NORM=16500

# Сколько собрано по искомому сегменту за сегодня. Вынесено в функцию,
# потому что спросить это нужно и в сообщении о заклинившем замке, то
# есть до обычного места подсчёта.
collected_today() {
  timeout 60 docker exec -i "$PG_CONTAINER" psql -qtA -U rent -d rent -c \
    "select count(distinct s.offer_id)
       from raw.offer_snapshot s
       join core.offer o using (source, offer_id)
      where s.snapshot_date = '$(date +%F)'
        and o.rooms_count in (1, 2);" \
    2>/dev/null | tr -d '[:space:]'
}

# Диск. У соседнего бокса он кончался трижды за сентябрь, и каждый раз
# молча: `setup` печатал «No space left on device» и выходил с кодом 0.
# База при кончившемся диске рискует больше всех, поэтому ниже двух
# гигабайт обход не начинается вовсе.
#
# Проверка по собственному разделу, а не по чужому: половина машины
# принадлежит другому проекту, и его файлы мы не считаем и не трогаем.
FREE_MB=$(df -Pm "$REPO" | awk 'NR==2 {print $4}')
if [ "${FREE_MB:-0}" -lt 2048 ]; then
  note "ОСТАНОВКА: свободно ${FREE_MB} МБ, это меньше двух гигабайт. Обход не запускаю, база дороже"
  notify disk-stop "$(date '+%d.%m %H:%M') ОСТАНОВКА: на боксе свободно ${FREE_MB} МБ из нужных 2048. Обход не запускается вовсе, день теряется. Лечить: ssh -p ${BOX_SSH_PORT} ${BOX_SSH_USER}@${BOX_SSH_HOST}, затем rm -rf ~/rent_msk/data/browser_profile/Default/Cache (куки не трогать)"
  exit 1
fi
if [ "${FREE_MB:-0}" -lt 5120 ]; then
  note "ВНИМАНИЕ: свободно всего ${FREE_MB} МБ"
  notify disk-low "$(date '+%d.%m %H:%M') ВНИМАНИЕ: на боксе свободно ${FREE_MB} МБ. Ниже 2048 обход встанет. Лечить: rm -rf ~/rent_msk/data/browser_profile/Default/Cache"
fi

# Идёт обход — сторожу делать нечего. Проверка по замку, а не по
# процессу: замок держит и ручной запуск тоже.
#
# Но замок врёт, когда прогон заклинил. 21.10.2026 ночной обход упёрся в
# блокировку площадки, встал уже после записи итога в журнал прогонов —
# на закрытии браузера или пересборке витрин — и держал каталог
# девятнадцать часов. Процессы были живы, поэтому ни один признак смерти
# не срабатывал: Chrome занимал 1,6 ГБ при лимите бокса в 3 ГиБ, от
# голода по памяти перестал отвечать и сам демон Docker. Сторож по
# прежнему правилу молчал весь день, плановый прогон в полдень вышел по
# замку, и день панели потерялся бы целиком, если бы не заметили руками.
#
# Поэтому у замка есть срок давности.
LOCK="$REPO/data/box.lock"
if [ -d "$LOCK" ]; then
  NOW=$(date +%s)
  LOCK_AGE_MIN=$(( (NOW - $(stat -c %Y "$LOCK")) / 60 ))

  # Тишина в журнале прогона — единственный признак клинча, видимый
  # снаружи: процесс жив, память занята, а данные не идут. Живой обход
  # пишет строку на каждую корзину, то есть раз в полминуты.
  #
  # Берётся журнал прогона (box_ДАТА_ЧАСЫ.log), а не журнал сторожа и не
  # дневной отчёт: шаблон box_2*.log отсекает box_watch.log и
  # box_report.log, которые пишутся каждые двадцать минут и тишины не
  # покажут никогда.
  RUN_LOG="$(ls -t "$LOG_DIR"/box_2*.log 2>/dev/null | head -n 1)"
  if [ -n "$RUN_LOG" ]; then
    QUIET=$(( (NOW - $(stat -c %Y "$RUN_LOG")) / 60 ))
  else
    # Журнала нет вовсе — считаем это молчанием: замок без журнала
    # прогона не объясняется ничем хорошим.
    QUIET="$QUIET_MIN"
  fi

  # Условия складываются, а не выбираются: снимать замок можно, только
  # когда он и стар, и нем. Шесть часов — вдвое дольше самого долгого
  # честного обхода (полный день собирается за два с половиной часа,
  # 12.10.2026 это заняло одиннадцать заходов, но ни один не шёл больше
  # трёх часов). Полчаса тишины у живого обхода невозможны: даже сбойная
  # корзина пишет предупреждение раз в полторы минуты.
  if [ "$LOCK_AGE_MIN" -ge $(( STALE_H * 60 )) ] && [ "$QUIET" -ge "$QUIET_MIN" ]; then
    note "ВНИМАНИЕ: замок держится $((LOCK_AGE_MIN / 60)) ч, журнал молчит $QUIET мин — обход заклинил, разбираю"

    # Порядок обязателен: сначала умирает браузер, только потом снимается
    # замок. Наоборот — и следующий обход войдёт вторым браузером в тот
    # же профиль Chrome и сломает сессию площадки обоим.
    #
    # Каждый вызов docker под timeout: при голоде по памяти демон не
    # отвечает вовсе, и 21.10.2026 `docker stop` с `docker kill` висели
    # минутами и вернули код 124. Сторож не имеет права встать сам.
    timeout 20 docker kill "$COLLECT_CONTAINER" >/dev/null 2>&1 \
      || note "  демон Docker не ответил, убиваю процессы обхода напрямую"

    # Чистый путь: убитый контейнер отпускает docker run, тот — скрипт
    # прогона, а его собственный trap снимает замок. Минута ожидания.
    for _ in $(seq 1 12); do
      [ -d "$LOCK" ] || break
      sleep 5
    done

    # Демон не справился — режем по процессам. Шаблоны узкие и
    # перечислены поимённо: в боксе чужих процессов нет, но угадывать
    # всё равно нельзя. Chrome ищется по своему профилю, потому что
    # просто «chrome» убил бы и браузер пробы.
    if [ -d "$LOCK" ]; then
      for PAT in 'etl\.collect' 'user-data-dir=.*browser_profile' 'Xvfb :99' 'box_daily\.sh'; do
        pkill -f "$PAT" 2>/dev/null
      done
      sleep 5
      for PAT in 'etl\.collect' 'user-data-dir=.*browser_profile' 'Xvfb :99'; do
        pkill -9 -f "$PAT" 2>/dev/null
      done
      sleep 2
    fi

    # Последняя мера — снять каталог самому. Именно rmdir, а не rm -rf:
    # замок обязан быть пустым каталогом, и если он не пуст, то это уже
    # не замок, и сносить его сторожу нельзя.
    if [ -d "$LOCK" ] && ! rmdir "$LOCK" 2>/dev/null; then
      note "ОСТАНОВКА: замок снять не удалось, обход не запускаю"
      notify lock-stuck "$(date '+%d.%m %H:%M') ОСТАНОВКА: замок держится $((LOCK_AGE_MIN / 60)) ч и снять его не удалось — каталог не пуст. Обход не запускается, день теряется. Лечить руками: ssh -p ${BOX_SSH_PORT} ${BOX_SSH_USER}@${BOX_SSH_HOST}, ls -la ~/rent_msk/data/box.lock"
      exit 1
    fi
    note "  замок снят, заклинивший обход остановлен — иду пробовать выдачу"
    # Сообщение одно и по итогу, а не по началу разбора: беда тут одна,
    # и важно в ней не «разбираю», а сколько дня осталось несобранным.
    STALE_COLLECTED="$(collected_today)"
    notify lock-stale "$(date '+%d.%m %H:%M') обход заклинил, замок снят сторожем (держался $((LOCK_AGE_MIN / 60)) ч, журнал молчал $QUIET мин). Собрано ${STALE_COLLECTED:-?} из $NORM по сегменту. Сторож добирает сам; если к вечеру не добрал: box_daily.sh narrow $(date +%F)"
  else
    exit 0
  fi
fi

# Таймаут здесь не про базу, а про демон Docker: при голоде по памяти он
# не отвечает вовсе, и без срока сторож повис бы на этой строке. Тики
# копились бы в cron молча, а день терялся бы ровно как 21.10.2026.
if ! timeout 60 docker exec "$PG_CONTAINER" pg_isready -U rent -d rent >/dev/null 2>&1; then
  note "база или демон Docker не отвечает, пропускаю"
  exit 0
fi

COLLECTED="$(collected_today)"
COLLECTED="${COLLECTED:-0}"

if [ "$COLLECTED" -ge "$ENOUGH" ]; then
  # Тишина намеренная: писать «всё хорошо» семьдесят раз в сутки незачем.
  exit 0
fi

# Имя контейнера пробы освобождается заранее. `--rm` снимает контейнер
# сам, но только если тот завершился: убитая по таймауту проба оставляет
# занятое имя, и все следующие пробы падают на конфликте имени — то есть
# сторож замолкает навсегда, ничего об этом не говоря.
timeout 20 docker rm -f rent_probe_watch >/dev/null 2>&1

# Проба. Профиль браузера тот же, что у обхода, — куки копятся в нём, а
# не заводятся заново на каждую проверку.
#
# Пять минут — с запасом: проба это два запроса, а страница сама сдаётся
# по таймауту за полторы минуты. Без срока зависший Chrome держал бы тик
# сторожа до конца суток.
# Лимит памяти по той же причине, что у обхода (см. box_daily.sh), но
# скромнее: проба открывает одну страницу выдачи и живёт секунды.
PROBE_OUT="$(timeout 300 docker run --rm \
  --name rent_probe_watch \
  --network host \
  --shm-size=1g \
  --memory=1024m \
  --memory-swap=1024m \
  -v "$REPO":/work \
  -w /work \
  --user "$(id -u):$(id -g)" \
  -e HOME=/tmp \
  -e TZ=Europe/Moscow \
  -e CHROME_NO_SANDBOX=1 \
  -e PYTHONUNBUFFERED=1 \
  -e PYTHONPATH=/work \
  "$IMAGE" \
  bash -c 'Xvfb :99 -screen 0 1440x900x24 >/tmp/xvfb.log 2>&1 &
           sleep 3
           DISPLAY=:99 python scripts/box_probe.py' 2>&1 | tail -n 1)"
# Код берётся от docker run, а не от tail: это обеспечивает pipefail,
# включённый в начале файла. Без него был бы всегда ноль.
PROBE_CODE=$?

if [ "$PROBE_CODE" = 124 ]; then
  # 124 — код timeout. Отдельной строкой, потому что это не отказ
  # площадки, а наша беда: проба не уложилась в срок, и это признак
  # того, что боксу нехорошо.
  note "1-2 комнаты: собрано $COLLECTED из $ENOUGH; проба не уложилась в 5 минут, боксу нехорошо"
  notify probe-timeout "$(date '+%d.%m %H:%M') ВНИМАНИЕ: проба сторожа не уложилась в 5 минут (код 124) — боксу нехорошо. Собрано $COLLECTED из $NORM по сегменту. Лечить: ssh -p ${BOX_SSH_PORT} ${BOX_SSH_USER}@${BOX_SSH_HOST}, затем free -m и docker ps"
  exit 0
fi

if [ "$PROBE_CODE" != 0 ]; then
  note "1-2 комнаты: собрано $COLLECTED из $ENOUGH; $PROBE_OUT"
  exit 0
fi

note "1-2 комнаты: собрано $COLLECTED из $ENOUGH; $PROBE_OUT — ЗАПУСКАЮ ОБХОД"

# Полный обход, а не узкий срез: сторож работает в дни, когда что-то уже
# потеряно, и добирать имеет смысл все комнатности сразу.
exec "$REPO/scripts/box_daily.sh" full
