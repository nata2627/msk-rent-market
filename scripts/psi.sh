# shellcheck shell=bash
# Сколько секунд хост простоял в ожидании памяти и диска за шаг прогона.
#
# Зачем. 25.11.2026 пульс поднял тревогу «хост ждет память, 5,1%», и по
# строке раз в пять минут виновника было не назвать: среднее за минуту
# совпало с концом дедупликации, вчерашний всплеск с шагом «Индекс», а
# про витрины, которые идут дольше всех, пульс не сказал ничего. Счетчик
# total в /proc/pressure копится с загрузки в микросекундах и не теряет
# ни секунды между замерами, поэтому разница на границах шага называет
# виновника точно. Счетчик общий на всю машину, а не на контейнер, и
# виден изнутри контейнера тоже.
#
# full, а не some: в full все задачи стоят разом, это и есть время, когда
# машина ничего не делала.

psi_full_us() {
  awk '$1 == "full" { split($5, a, "="); print a[2]; exit }' "/proc/pressure/$1" 2>/dev/null
}

psi_mark() {
  PSI_MEM0="$(psi_full_us memory)"
  PSI_IO0="$(psi_full_us io)"
}

# Хвост строки «готово»: «, ожидание памяти 3,1 с, диска 40,2 с». Пусто,
# если счетчиков нет (ядро без PSI) или отметки не было.
psi_since() {
  local m i
  m="$(psi_full_us memory)"
  i="$(psi_full_us io)"
  [ -n "$m" ] && [ -n "$i" ] && [ -n "${PSI_MEM0:-}" ] && [ -n "${PSI_IO0:-}" ] || return 0
  awk -v m="$m" -v m0="$PSI_MEM0" -v i="$i" -v i0="$PSI_IO0" \
    'BEGIN { s = sprintf(", ожидание памяти %.1f с, диска %.1f с", (m - m0) / 1e6, (i - i0) / 1e6); gsub(/\./, ",", s); print s }'
}
