# Предохранитель от бесконечного дробления.
#
# Открытый сверху диапазон [a, +inf) делится всегда: 60->120->240 тысяч и так
# без конца. В рабочем обходе это безопасно, потому что делением управляет
# заявленное площадкой число результатов, и на дорогом хвосте оно быстро
# падает ниже порога. Но если площадка начнёт врать и всегда заявлять число
# выше порога, рекурсия не остановится. Предел глубины делает такой сценарий
# невозможным: корзина просто пометится усечённой и попадёт в журнал недобора.
#
# 12 с запасом: реальная глубина это район (1) + комнатность (1) + несколько
# делений цены, то есть 4-6.
