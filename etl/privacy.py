"""Удаление персональных данных до записи в базу.

Почему это отдельный модуль, а не пара строк в разборе. Площадка отдаёт
в карточке телефон автора и его имя: у 52 181 сохранённого снимка телефон
был во всех, имя автора — в 30 994. Для физического лица, собирающего
данные для себя, это законно (152-ФЗ, ст. 2 ч. 2 — обработка для личных
и семейных нужд). Но проект идёт в публичный репозиторий и в портфолио,
и там это перестаёт работать: любой скриншот, любая выгрузка, любой
открытый наружу дашборд превращается в распространение чужих
персональных данных.

Ни для одного из трёх вопросов исследования телефон и имя не нужны.
Поэтому они не «прячутся при показе», а не попадают в базу вовсе.

Что сохраняется и почему:

* тип продавца (собственник / агентство / частный риелтор) — объясняющая
  переменная регрессии;
* идентификатор продавца в виде хеша — по нему считается, сколько
  объявлений у одного автора, но восстановить, кто это, нельзя;
* стаж и рейтинг — публичные характеристики профиля, не идентифицирующие.

Хеш солёный и усечённый. Соль лежит в .env и в репозиторий не попадает:
без неё хеш нельзя сопоставить с исходным идентификатором перебором,
а перебор тут реален — идентификаторов у площадки конечное число.
"""
from __future__ import annotations

import hashlib
import os
import re

# Соль берётся из окружения. Дефолт нужен, чтобы проект запускался из
# коробки; для публикуемых расчётов его стоит переопределить в .env.
SALT = os.getenv("SELLER_ID_SALT", "msk-rent-market-local")

# Поля карточки, которые не должны попасть в хранилище ни в каком виде.
DROP_TOP_LEVEL = ("phones",)

# Идентификаторы автора объявления. Их четыре, и лежат они в разных
# местах — три на верхнем уровне карточки и один внутри user. Первая
# версия захешировала только user.cianUserId, а остальные три остались
# как есть, то есть вычистка была видимостью: автор по-прежнему
# опознавался по трём полям из четырёх.
#
# Идентификатор объявления (id, cianId) сюда НЕ входит: он публичный,
# по нему открывается страница, и хешировать его значило бы потерять
# связь с площадкой.
SELLER_ID_FIELDS = ("userId", "cianUserId", "publishedUserId")

# Ключи, которые вычищаются ВЕЗДЕ, на любой глубине: по имени они
# однозначны и ничего кроме персональных данных не означают.
DROP_ANYWHERE = (
    "phones", "phoneNumbers", "profileUri", "agentAvatarUrl", "billingInfo",
)

# Ключи, которые вычищаются ТОЛЬКО внутри блока автора.
#
# Разделение не косметическое. Ключ name есть у агентства, у станции
# метро, у части адреса и у района. Глобальное удаление по имени снесло
# всю географию — так и случилось в первой версии рекурсивного обхода,
# и это поймали тесты разбора адреса.
DROP_IN_USER = (
    "agencyName", "companyName", "name", "firstName", "lastName",
)

# Телефон в свободном тексте описания. Встречается редко, но оставлять
# его бессмысленно: мы всё равно выбрасываем телефон из анкеты.
PHONE_IN_TEXT = re.compile(
    r"(?:\+?7|8)[\s\-(]?9\d{2}[\s\-)]?\d{3}[\s\-]?\d{2}[\s\-]?\d{2}")


def hash_seller_id(value) -> str | None:
    """Устойчивый псевдоним продавца.

    Устойчивый — значит один и тот же автор получает один и тот же хеш
    в разных запусках, иначе «сколько объявлений у этого агентства»
    посчитать нельзя. Необратимый — значит по базе нельзя составить
    список людей.
    """
    if value in (None, ""):
        return None
    return hashlib.sha256(f"{SALT}:{value}".encode()).hexdigest()[:16]


def scrub_text(text: str | None) -> str | None:
    """Замаскировать телефон в свободном тексте."""
    if not text:
        return text
    return PHONE_IN_TEXT.sub("[телефон удалён]", text)


def scrub_payload(payload: dict) -> dict:
    """Карточка объявления без персональных данных.

    Обход рекурсивный, и это не перестраховка. Первая версия перечисляла
    места — верхний уровень и блок user — и пропустила идентификатор
    автора во вложенном agentAvailability. Перечислять места в чужой
    структуре нельзя: площадка добавит поле и не спросит. Правило
    задаётся по ИМЕНИ ключа и применяется на любой глубине.

    Но не всякий ключ однозначен: name есть и у агентства, и у станции
    метро. Такие вычищаются только внутри блока автора, и эта граница
    передаётся флагом вниз по обходу.

    Возвращает копию: исходный словарь остаётся нетронутым, потому что
    из него же разбираются поля для панели.
    """
    def walk(node, in_user: bool = False):
        if isinstance(node, list):
            return [walk(x, in_user) for x in node]
        if not isinstance(node, dict):
            return node

        out = {}
        for key, value in node.items():
            if key in DROP_ANYWHERE:
                continue
            if in_user and key in DROP_IN_USER:
                continue
            if key in SELLER_ID_FIELDS and value is not None:
                out[key] = hash_seller_id(value)
                continue
            if key == "description" and isinstance(value, str):
                out[key] = scrub_text(value)
                continue
            out[key] = walk(value, in_user or key == "user")
        return out

    return walk(payload)
